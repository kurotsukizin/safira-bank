BEGIN;
CREATE TABLE public.usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 senha_hash VARCHAR(255) NOT NULL, perfil VARCHAR(20) NOT NULL,
 status VARCHAR(20) NOT NULL, criado_em TIMESTAMP NOT NULL
);
CREATE TABLE public.conta_bancaria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 agencia VARCHAR(4) NOT NULL, numero VARCHAR(12) NOT NULL,
 status VARCHAR(20) NOT NULL, criada_em TIMESTAMP NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES public.usuario(id),
 UNIQUE(agencia,numero)
);
CREATE TABLE public.transacao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 valor NUMERIC(19,2) NOT NULL CHECK(valor>0), status VARCHAR(30) NOT NULL,
 criada_em TIMESTAMP NOT NULL, concluida_em TIMESTAMP,
 descricao VARCHAR(255),
 conta_origem_id BIGINT NOT NULL REFERENCES public.conta_bancaria(id),
 conta_destino_id BIGINT NOT NULL REFERENCES public.conta_bancaria(id),
 CHECK(conta_origem_id<>conta_destino_id)
);
CREATE TABLE public.lancamento_financeiro (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('CREDITO','DEBITO')),
 valor NUMERIC(19,2) NOT NULL CHECK(valor>0), criado_em TIMESTAMP NOT NULL,
 descricao VARCHAR(255), conta_id BIGINT NOT NULL REFERENCES public.conta_bancaria(id),
 transacao_id BIGINT NOT NULL REFERENCES public.transacao(id)
);
CREATE INDEX idx_conta_usuario ON public.conta_bancaria(usuario_id);
CREATE INDEX idx_lancamento_conta_data ON public.lancamento_financeiro(conta_id,criado_em DESC,id DESC);
CREATE INDEX idx_lancamento_transacao ON public.lancamento_financeiro(transacao_id);
COMMIT;
